#!/usr/bin/env python3
"""
Builds the OPENRNDR guide as a single PDF from the Markdown generated by
dokgen (build/dokgen/zola/content) and the media in build/dokgen/zola/static.

Pipeline:
  1. Collect all pages in navigation order (front matter `weight`).
  2. Strip the TOML front matter, replace the <video> / <img> HTML that
     dokgen emits with Typst figures, and wrap each page in a fenced div
     carrying its path and depth.
  3. pandoc (with guide.lua) turns the combined Markdown into Typst:
     heading levels are shifted by depth, heading ids are made unique per
     page and `@/page.md#anchor` links become links inside the PDF.
  4. typst compiles the result into a PDF.

Requirements: Python 3.11+, pandoc 3.x and typst 0.13+ on PATH
(or pass --pandoc / --typst).

Usage, from the repository root:
  python3 scripts/pdf/build_pdf.py
  python3 scripts/pdf/build_pdf.py --font "Noto Serif" --sans-font "Noto Sans"
"""

import argparse
import datetime
import os
import re
import shutil
import struct
import subprocess
import sys
import tomllib
from dataclasses import dataclass
from pathlib import Path

HERE = Path(__file__).resolve().parent
REPO = HERE.parent.parent
SITE_URL = "https://guide.openrndr.org"

# Widest media in the guide is 770 px; it gets this fraction of the text width.
MAX_IMAGE_WIDTH_PX = 770
MAX_IMAGE_WIDTH_PCT = 85


@dataclass
class Page:
    path: str        # relative to content dir, e.g. "drawing/renderTargets.md"
    depth: int       # 1 = chapter, 2 = page inside a section
    title: str
    body: str


# ---------------------------------------------------------------------------
# Collecting pages

def read_page(file: Path) -> tuple[dict, str]:
    text = file.read_text(encoding="utf-8")
    m = re.match(r"\A\+\+\+\n(.*?)\n\+\+\+\n?(.*)\Z", text, re.S)
    if not m:
        return {}, text
    return tomllib.loads(m.group(1)), m.group(2)


def weight_of(front: dict) -> int:
    return front.get("weight", front.get("extra", {}).get("weight", 0))


def collect(section_dir: Path, content_dir: Path, depth: int) -> list[Page]:
    """Section index first, then pages and subsections sorted by weight."""
    pages: list[Page] = []
    index = section_dir / "_index.md"
    if index.exists():
        front, body = read_page(index)
        pages.append(Page(index.relative_to(content_dir).as_posix(),
                          max(depth, 1), front.get("title", ""), body))

    children = []  # (weight, name, kind, path)
    for child in section_dir.iterdir():
        if child.is_dir() and (child / "_index.md").exists():
            front, _ = read_page(child / "_index.md")
            children.append((weight_of(front), child.name, "dir", child))
        elif child.suffix == ".md" and child.name != "_index.md":
            front, _ = read_page(child)
            children.append((weight_of(front), child.name, "page", child))

    # The content root's children are chapters (depth 1), like its index.
    # Like the site navigation, pages go before subsections of equal weight.
    child_depth = max(depth + 1, 1)
    for _, _, kind, child in sorted(children, key=lambda c: (c[0], c[2] == "dir", c[1])):
        if kind == "dir":
            pages += collect(child, content_dir, child_depth)
        else:
            front, body = read_page(child)
            pages.append(Page(child.relative_to(content_dir).as_posix(),
                              child_depth, front.get("title", ""), body))
    return pages


# ---------------------------------------------------------------------------
# Media

def image_width_px(file: Path) -> int | None:
    """Pixel width of a PNG or JPEG file, without third-party libraries."""
    try:
        data = file.read_bytes()
    except OSError:
        return None
    if data[:8] == b"\x89PNG\r\n\x1a\n":
        return struct.unpack(">I", data[16:20])[0]
    if data[:2] == b"\xff\xd8":
        i = 2
        while i + 9 < len(data):
            if data[i] != 0xFF:
                i += 1
                continue
            marker = data[i + 1]
            if marker in (0xC0, 0xC1, 0xC2):
                return struct.unpack(">H", data[i + 7:i + 9])[0]
            i += 2 + struct.unpack(">H", data[i + 2:i + 4])[0]
    return None


def typst_str(s: str) -> str:
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


class Media:
    def __init__(self, static_dir: Path, typst_prefix: str):
        self.static_dir = static_dir
        self.prefix = typst_prefix  # static dir as seen from the Typst root
        self.missing: list[str] = []

    def _resolve(self, src: str) -> tuple[str, str] | None:
        """Returns (typst path, width) or None if the file does not exist."""
        file = self.static_dir / src.lstrip("/")
        if not file.is_file():
            self.missing.append(src)
            return None
        px = image_width_px(file)
        pct = MAX_IMAGE_WIDTH_PCT if px is None else \
            min(100, round(px / MAX_IMAGE_WIDTH_PX * MAX_IMAGE_WIDTH_PCT))
        return self.prefix + "/" + src.lstrip("/"), f"{pct}%"

    @staticmethod
    def _raw(typst: str) -> str:
        return f"\n\n```{{=typst}}\n{typst}\n```\n\n"

    def video(self, m: re.Match) -> str:
        poster, src = m.group("poster"), m.group("src")
        url = SITE_URL + src if src.startswith("/") else src
        resolved = self._resolve(poster)
        if not resolved:
            return f"\n\n*[Video: <{url}>]*\n\n"
        path, width = resolved
        return self._raw(
            f"#guide-video({typst_str(path)}, {typst_str(url)}, width: {width})")

    def image(self, m: re.Match) -> str:
        resolved = self._resolve(m.group("src"))
        if not resolved:
            return f"\n\n*[Missing image: {m.group('src')}]*\n\n"
        path, width = resolved
        return self._raw(f"#guide-image({typst_str(path)}, width: {width})")


VIDEO_RE = re.compile(
    r'<video\b[^>]*\bposter="(?P<poster>[^"]+)"[^>]*>\s*'
    r'<source\b[^>]*\bsrc="(?P<src>[^"]+)"[^>]*>\s*</video>', re.S)
IMG_RE = re.compile(r'<img\b[^>]*\bsrc="(?P<src>[^"]+)"[^>]*>')


# ---------------------------------------------------------------------------
# Markdown assembly

def prepare(page: Page, media: Media) -> str:
    body = VIDEO_RE.sub(media.video, page.body)
    body = IMG_RE.sub(media.image, body)
    if "<video" in body or "<img" in body:
        print(f"warning: unconverted HTML media in {page.path}", file=sys.stderr)

    # Every page must start with a level-1 heading: guide.lua turns it into
    # the page heading. Some pages start with ## or text; use the nav title.
    first_line = next((l for l in body.splitlines() if l.strip()), "")
    if not re.match(r"#\s", first_line):
        body = f"# {page.title}\n\n{body}"

    fence = ":" * 8
    return (f'{fence} {{.guide-page path="{page.path}" depth="{page.depth}"}}\n'
            f"{body.strip()}\n\n{fence}\n")


def find_tool(name: str, explicit: str | None) -> str:
    tool = explicit or os.environ.get(name.upper()) or shutil.which(name)
    if not tool:
        sys.exit(f"error: '{name}' not found. Install it or pass --{name} PATH.")
    return tool


def run(cmd: list[str]) -> None:
    print("+ " + " ".join(cmd), file=sys.stderr)
    subprocess.run(cmd, check=True)


def pandoc_version(pandoc: str) -> tuple[int, ...]:
    out = subprocess.run([pandoc, "--version"], capture_output=True,
                         text=True, check=True).stdout
    m = re.search(r"(\d+)\.(\d+)(?:\.(\d+))?", out)
    return tuple(int(x or 0) for x in m.groups()) if m else (0,)


def main() -> None:
    zola = REPO / "build" / "dokgen" / "zola"
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--content", type=Path, default=zola / "content")
    ap.add_argument("--static", type=Path, default=zola / "static")
    ap.add_argument("--out", type=Path,
                    default=REPO / "build" / "dokgen" / "pdf" / "openrndr-guide.pdf")
    ap.add_argument("--pandoc")
    ap.add_argument("--typst")
    ap.add_argument("--font", default="Libertinus Serif", help="body font")
    ap.add_argument("--sans-font", default="Libertinus Serif",
                    help="font for headings, cover and running headers")
    ap.add_argument("--mono-font", default="DejaVu Sans Mono")
    ap.add_argument("--highlight", choices=["typst", "pandoc"], default="typst",
                    help="who highlights code: typst natively, or pandoc "
                         "(skylighting, Tango style; needs pandoc 3.8+)")
    ap.add_argument("--typ-only", action="store_true",
                    help="stop after writing the .typ file "
                         "(e.g. to iterate with `typst watch`)")
    args = ap.parse_args()

    content = args.content.resolve()
    static = args.static.resolve()
    out_pdf = args.out.resolve()
    work = out_pdf.parent
    work.mkdir(parents=True, exist_ok=True)
    if not content.is_dir():
        sys.exit(f"error: {content} not found. Run ./gradlew dokgen first.")

    # Typst only reads files below --root, so use the common ancestor of the
    # static folder and the output folder.
    root = Path(os.path.commonpath([static, work]))
    prefix = "/" + static.relative_to(root).as_posix() if static != root else ""
    media = Media(static, prefix)

    pages = collect(content, content, 0)
    print(f"{len(pages)} pages", file=sys.stderr)
    md = work / "openrndr-guide.md"
    md.write_text("\n".join(prepare(p, media) for p in pages), encoding="utf-8")
    for src in media.missing:
        print(f"warning: missing media file {src}", file=sys.stderr)

    cover = "/media/what-is-001-thumb.jpg"
    cover_meta = []
    if (static / cover.lstrip("/")).is_file():
        # Variables are inserted verbatim, metadata would be escaped as markup.
        cover_meta = ["--variable", f"cover-image={prefix}{cover}"]

    pandoc = find_tool("pandoc", args.pandoc)
    typ = work / "openrndr-guide.typ"
    cmd = [
        pandoc, str(md),
        "--from", "commonmark_x+smart",
        "--to", "typst",
        "--standalone",
        "--template", str(HERE / "template.typ"),
        "--lua-filter", str(HERE / "guide.lua"),
        "--metadata", "title=OPENRNDR GUIDE",
        "--metadata", "subtitle=A creative coding framework for Kotlin",
        "--metadata", f"date={datetime.date.today().isoformat()}",
        "--metadata", f"site-url={SITE_URL}",   # for guide.lua
        "--variable", f"site-url={SITE_URL}",   # for template.typ
        "--metadata", f"static-prefix={prefix}",
        *cover_meta,
        "--variable", f"mainfont={args.font}",
        "--variable", f"sansfont={args.sans_font}",
        "--variable", f"monofont={args.mono_font}",
        "--output", str(typ),
    ]
    if args.highlight == "pandoc":
        if pandoc_version(pandoc) < (3, 8):
            sys.exit("error: --highlight pandoc needs pandoc 3.8 or newer")
        cmd += ["--syntax-highlighting", "tango"]
    elif pandoc_version(pandoc) >= (3, 8):
        cmd += ["--syntax-highlighting", "idiomatic"]
    run(cmd)

    if args.typ_only:
        print(f"wrote {typ}", file=sys.stderr)
        return

    typst = find_tool("typst", args.typst)
    run([typst, "compile", "--root", str(root), str(typ), str(out_pdf)])
    print(f"wrote {out_pdf}", file=sys.stderr)


if __name__ == "__main__":
    main()
