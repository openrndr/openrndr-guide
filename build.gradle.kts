tasks.register("add IDE file scopes") {
    description = "Adds scopes for showing only specific file types the file browser"
    group = " ★ OPENRNDR"
    val scopesFolder = File("${project.projectDir}/.idea/scopes")
    scopesFolder.mkdirs()

    val files = listOf(
        "Code" to "file:*.kt||file:*.frag||file:*.vert||file:*.glsl",
        "Text" to "file:*.txt||file:*.md||file:*.xml||file:*.json",
        "Gradle" to "file[*buildSrc*]:*/||file:*gradle.*||file:*.gradle||file:*/gradle-wrapper.properties||file:*.toml",
        "Media" to "file:*.png||file:*.jpg||file:*.dds||file:*.exr||file:*.mp3||file:*.wav||file:*.mp4||file:*.mov||file:*.svg"
    )
    files.forEach { (name, pattern) ->
        val file = File(scopesFolder, "__$name.xml")
        if (!file.exists()) {
            file.writeText(
                """
                    <component name="DependencyValidationManager">
                      <scope name=" ★ $name" pattern="$pattern" />
                    </component>
                    """.trimIndent()
            )
        }
    }
}

/**
 * Writes the ORX modules the guide depends on (the `orx` bundle in
 * gradle/libs.versions.toml) as a `dependencies {}` block. The
 * publishExamples workflow appends it to the build.gradle.kts of
 * openrndr-template to build openrndr-examples, so the examples
 * repository always has the same ORX modules as the guide.
 *
 * The modules are looked up by artifact name in the template's `orx`
 * version catalog, as catalog aliases don't always match artifact names
 * (`orx-kinect-v1` is `kinect-v1-core`), and versions come from the template.
 */
tasks.register("examplesRepoDependencies") {
    description = "Writes the ORX dependencies for the openrndr-examples repository"
    group = " ★ OPENRNDR"

    val modules = libs.bundles.orx.map { bundle -> bundle.map { it.module.name }.sorted() }
    val output = layout.buildDirectory.file("examples-repo/build.gradle.kts.append")
    inputs.property("modules", modules)
    outputs.file(output)

    doLast {
        val list = modules.get().joinToString(",\n") { "        \"$it\"" }
        output.get().asFile.writeText(
            """
            |
            |
            |// Added by the openrndr-guide publishExamples workflow:
            |// the ORX modules used by the guide (generated by `./gradlew examplesRepoDependencies`)
            |dependencies {
            |    val orxCatalog = versionCatalogs.named("orx")
            |    val aliasByModule = orxCatalog.libraryAliases.associateBy { alias ->
            |        orxCatalog.findLibrary(alias).get().get().module.name
            |    }
            |    listOf(
            |$list
            |    ).forEach { module ->
            |        val alias = aliasByModule[module] ?: error("${'$'}module not found in the orx version catalog")
            |        implementation(orxCatalog.findLibrary(alias).get())
            |    }
            |}
            |""".trimMargin()
        )
    }
}
