package org.openrndr.dokgen

import org.openrndr.dokgen.sourceprocessor.SourceProcessor
import java.io.File
import java.nio.file.Path

/**
 * Returns a relative [Path] between two [File] instances.
 * Potentially could be replaced with `File.toRelativeString()`
 */
fun File.relativeDir(file: File): Path {
    return toPath().relativize(file.toPath()).parent ?: File("").toPath()
}

/**
 * Takes a [Path] and returns a `.` separated String in which
 * non-valid package names are escaped with backticks.
 */
fun Path.escape() = joinToString(".") { part ->
    val str = part.toString()
    val special = str.any { ch -> !ch.isLetter() }
    if (special) "`$str`" else str
}

fun examplesPackageDirective(path: Path): String {
    val pathEscaped = path.escape()
    return "examples" + if(pathEscaped.isNotEmpty()) ".$pathEscaped" else ""
}

/** A TOML basic string: quoted, with backslashes, quotes and control characters escaped */
fun tomlString(s: String): String = buildString {
    append('"')
    s.forEach { c ->
        when (c) {
            '\\' -> append("\\\\")
            '"' -> append("\\\"")
            '\n' -> append("\\n")
            '\r' -> append("\\r")
            '\t' -> append("\\t")
            else -> if (c < ' ') append("\\u%04x".format(c.code)) else append(c)
        }
    }
    append('"')
}

object DokGen {
    /**
     * @param ktFileLocation .kt source path relative to project root
     * @param title value of the `@file:Title` annotation
     * @param location where the page goes in the Zola site
     * @param aliases values of the `@file:Aliases` annotation
     * @return Zola front matter (TOML) to put at the top of a Markdown file
     */
    fun zolaFrontMatter(
        ktFileLocation: String,
        title: String,
        location: GuideLocation,
        aliases: List<String>
    ): String {
        val allAliases = (listOfNotNull(location.legacyUrl) + aliases.map { it.trim('/') }).distinct()
        return buildString {
            appendLine("+++")
            appendLine("# File generated by dokgen. Do not edit.")
            appendLine("# Edit '$ktFileLocation' instead.")
            appendLine("title = ${tomlString(title)}")
            appendLine("weight = ${location.weight}")
            if (location.isSection) {
                appendLine("sort_by = \"weight\"")
            }
            if (allAliases.isNotEmpty()) {
                appendLine("aliases = [${allAliases.joinToString(", ") { tomlString(it) }}]")
            }
            appendLine()
            appendLine("[extra]")
            appendLine("# Zola does not expose `weight` to templates. Used to sort the navigation.")
            appendLine("weight = ${location.weight}")
            appendLine("source = ${tomlString(ktFileLocation)}")
            appendLine("+++")
            appendLine()
        }
    }

    /**
     * Processes Guide source .kt files. It reads each file and produces
     * multiple files for each input:
     * - a Markdown document visible in the online website.
     * - zero or more .kt files to run and produce media
     *   to include in the online website.
     * - zero or more .kt files to upload examples repository in GitHub
     *
     * @param sourceFiles list of .kt files to process
     * @param sourcesRoot root location of the source .kt files
     * @param mdOutputDir location where to write markdown files
     * @param examplesOutputDir location where to write media-producing .kt programs
     * @param examplesForExportOutputDir location where to write .kt examples for GitHub
     * @param webRootUrl URL where GitHub examples will be accessible
     */
    fun processSources(
        sourceFiles: List<File>,
        sourcesRoot: File,
        mdOutputDir: File,
        examplesOutputDir: File,
        examplesForExportOutputDir: File,
        webRootUrl: String?
    ) {
        // Handle deleted files first: when a file is renamed but keeps its
        // URL (e.g. C90_Events.kt -> C090_Events.kt) the new page must win.
        sourceFiles.sortedBy { it.exists() }.forEach { sourceFile ->
            when (sourceFile.extension) {
                "md" -> throw NotImplementedError(
                    "Latest DokGen supports only .kt files " +
                            "but ${sourceFile.absolutePath} was found. " +
                            "Please convert it to .kt."
                )

                "kt" -> {
                    if (!sourceFile.exists()) {
                        // Deleted or renamed: remove its page so it doesn't linger in the site
                        val stale = File(
                            mdOutputDir,
                            GuideLocation.of(sourceFile.toRelativeString(sourcesRoot)).contentPath
                        )
                        if (stale.delete()) println("removed $stale")
                        return@forEach
                    }
                    val fileContents = sourceFile.readText().replace("\r\n", "\n")

                    val packageDirective = examplesPackageDirective(
                        sourcesRoot.relativeDir(sourceFile)
                    )

                    // A. actual dir, name and path (from a path on disk)
                    val fileDir = sourceFile.parentFile.toRelativeString(sourcesRoot)
                    val fileName = sourceFile.nameWithoutExtension
                    val filePath = sourceFile.toRelativeString(sourcesRoot)

                    val mkLink = webRootUrl?.let {
                        { index: Int ->
                            val paddedIndex = "$index".padStart(3, '0')
                            "$it/examples/$fileDir/$fileName$paddedIndex.kt"
                        }
                    }

                    // Runnable examples are placed and named after the location
                    // derived from the file path (ignoring any @file:URL override)
                    val examplesLocation = GuideLocation.of(filePath)

                    val result = try {
                        SourceProcessor.process(
                            fileContents,
                            packageDirective = packageDirective,
                            runnablePackageDirective = examplesPackageDirective(
                                File(examplesLocation.urlDir).toPath()
                            ),
                            mkLink = mkLink
                        )
                    } catch(e: IllegalArgumentException) {
                        println("\nError in $filePath")
                        println(e.message)
                        return@forEach
                    }

                    // B. location in the Zola site (from the dir and file names)
                    val location = GuideLocation.of(filePath, result.annotations["URL"])
                    val urlDir = examplesLocation.urlDir
                    val urlName = examplesLocation.name

                    // 1. Write Markdown file
                    val mdTarget = File(mdOutputDir, location.contentPath)
                    mdTarget.parentFile.mkdirs()
                    val fileRelPath = "$DOCS_DIR/${filePath.replace(File.separatorChar, '/')}"
                    val header = zolaFrontMatter(
                        fileRelPath, result.annotations["Title"]!!, location, result.aliases
                    )
                    mdTarget.writeText(header + result.doc)

                    // 2. Write .kt examples to generate media
                    val examplesOutDir = File(examplesOutputDir, urlDir)
                    examplesOutDir.mkdirs()
                    result.appSources.forEachIndexed { index, s ->
                        val paddedIndex = "$index".padStart(3, '0')
                        // Convert first letter to capital
                        // otherwise JVM doesn't find the class
                        // in `project.javaexec`
                        val urlNameCapital = urlName.replaceFirstChar {
                            it.uppercase()
                        }
                        val sampleOutFile = File(
                            examplesOutDir,
                            "$urlNameCapital$paddedIndex.kt"
                        )
                        println("writing runnable example to $sampleOutFile")
                        sampleOutFile.writeText(s)
                    }

                    // 3. Write .kt examples for GitHub repo
                    val examplesForExportOutDir =
                        File(examplesForExportOutputDir, fileDir)
                    examplesForExportOutDir.mkdirs()
                    result.appSourcesForExport.forEachIndexed { index, s ->
                        val paddedIndex = "$index".padStart(3, '0')
                        val sampleOutFile = File(
                            examplesForExportOutDir,
                            "$fileName$paddedIndex.kt"
                        )
                        println("writing exported example to $sampleOutFile")
                        sampleOutFile.writeText(s)
                    }
                }
            }
        }
    }

    fun getExamplesClassNames(sourceFiles: List<File>, sourcesRoot: File): List<String> {
        return sourceFiles.filter {
            it.extension == "kt"
        }.map { file ->
            val pd = examplesPackageDirective(sourcesRoot.relativeDir(file))
                    .filter { ch -> ch != '`' }
            "$pd.${file.nameWithoutExtension}Kt"
        }
    }
}

